"""R2-D2 CLI: durable core verbs (``raise``/``done``/``status``/``events``) and
the Task 14 OPERATOR grant verbs (``grant issue|list|revoke``).

Grant verbs are OPERATOR verbs, NOT agent tools:

* They require an explicit ``--operator`` marker and refuse daemon/model
  execution (``--recovery``/``--automatic`` flags or a marker in the
  daemon/model denylist). Each refusal is LEDGERED as a deny hit under the
  ``guard-grant-cli-verb`` rule id, so a model/daemon attempt is visible, not
  silent.
* They are NOT part of the executor's operation allowlist, so no model tool
  path can reach them through the daemon.
* The nonce is GENERATED by the grant store (the issuer), never accepted from
  the CLI or from an incident record — a grant cannot mint its own authority.

Threat model (honest): the operator marker is a *procedural* record, not an
identity proof. Same-UID code can lie about it or edit the grant files
directly; these verbs enforce the behavior and record the action, and are not
an OS security boundary.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time

from operator_guards.ed209 import capabilities, cli as ed209_cli
from operator_guards.ed209.ledger import DEFAULT_HITS_DB, HitLedger
from operator_guards.ed209.rules import RulesError, load_rules
from operator_guards.r2d2 import handlers, observer
from operator_guards.r2d2.authz import GRANT_SCOPES, GrantError, GrantStore
from operator_guards.r2d2.claims import proc_start_time
from operator_guards.r2d2.schema import (
    LIFECYCLE_PHASES,
    SEVERITIES,
    IncidentError,
)
from operator_guards.r2d2.store import (
    DEFAULT_STATE_ROOT,
    IncidentStore,
    StoreCorruptionError,
    StoreError,
)

# Ledger rule id recorded whenever a grant verb is refused as daemon/model
# execution (a protected guard rule; the refusal is durable and queryable).
GRANT_VERB_DENY_RULE_ID = "guard-grant-cli-verb"

# Operator markers that present as daemon/model execution and are refused.
GRANT_CLI_DENIED_MARKERS = frozenset(
    {"automatic", "auto", "recovery", "agent", "self", "r2d2", "daemon", "model", "tool"}
)


class OperatorActionRefused(Exception):
    """Raised when a grant verb is invoked as daemon/model execution."""


def _store(args) -> IncidentStore:
    return IncidentStore(args.root or DEFAULT_STATE_ROOT)


def _cmd_raise(args) -> int:
    record = {
        "id": args.id,
        "severity": args.severity,
        "symptom": args.symptom,
        "phase": args.phase,
        "dedupe_key": args.dedupe_key or args.id,
    }
    for field in ("host_id", "profile_id", "client_id", "session_id", "notification"):
        value = getattr(args, field)
        if value is not None:
            record[field] = value
    if args.observed:
        record["observed"] = list(args.observed)
    inc = _store(args).raise_incident(record)
    # Printed only after the store returned (event + snapshot durable).
    print(inc.id)
    return 0


def _cmd_done(args) -> int:
    inc = _store(args).done(args.id, proof=args.proof, reason=args.reason)
    print(f"{inc.id}\t{inc.phase}")
    return 0


def _format_incident(inc) -> str:
    return f"{inc.id}\t{inc.phase}\t{inc.severity}\t{inc.symptom}"


def _cmd_status(args) -> int:
    store = _store(args)
    if args.id:
        inc = store.get_incident(args.id)
        if inc is None:
            print(f"error: no incident {args.id!r}", file=sys.stderr)
            return 1
        print(_format_incident(inc))
        return 0
    incidents = store.list_incidents()
    if not incidents:
        print("(no incidents)")
        return 0
    for inc in incidents:
        print(_format_incident(inc))
    return 0


def _cmd_events(args) -> int:
    events = _store(args).list_events(limit=args.limit)
    if not events:
        print("(no events)")
        return 0
    for ev in events:
        print(f"{ev['seq']}\t{ev['type']}\t{ev['incident_id']}")
    return 0


# ---------------------------------------------------------------------------
# watch (DRY-RUN observer) + doctor (read-only report) — Task 15
# ---------------------------------------------------------------------------
# Both verbs are READ-ONLY. They never instantiate IncidentStore's recovery
# path (which creates dirs and may reconcile-write snapshots) and never touch
# the observer's mutating paths (raise_incident / alert writer / heartbeat
# writer). They read raw files only, so a tree snapshot taken before and after
# is byte-identical.

_TERMINAL_PHASES = frozenset({"resolved", "escalated"})


def _read_incidents_readonly(root: str) -> list[dict]:
    """Read incident snapshots DIRECTLY from ``<root>/incidents/*.json``.

    Never via ``IncidentStore`` (whose recovery pass ``os.makedirs`` the state
    root and can reconcile-write snapshots); this is a pure directory read.
    """
    out: list[dict] = []
    try:
        names = sorted(os.listdir(os.path.join(root, "incidents")))
    except OSError:
        return out
    for name in names:
        if not name.endswith(".json"):
            continue
        try:
            with open(os.path.join(root, "incidents", name), encoding="utf-8") as f:
                data = json.load(f)
        except (OSError, ValueError):
            continue
        if isinstance(data, dict):
            out.append(data)
    return out


def _cmd_watch(args) -> int:
    """Dry-run observer: report what WOULD alert/escalate. Writes NOTHING."""
    root = args.root or DEFAULT_STATE_ROOT
    now = time.monotonic()

    ts = observer.read_heartbeat_file(root)
    if ts is None:
        print("supervisor: absent (would local-alert)")
    elif now - ts > observer.SUPERVISOR_STALE_SECONDS:
        print(
            f"supervisor: stale ({now - ts:.0f}s > "
            f"{observer.SUPERVISOR_STALE_SECONDS:.0f}s) (would local-alert)"
        )
    else:
        print("supervisor: fresh")

    clients = observer.list_client_records(root)
    if not clients:
        print("clients: none")
    for client_id in sorted(clients):
        client = clients[client_id]
        if client.status == observer.CLIENT_STATUS_ENDED:
            print(f"client {client_id}: ended (skipped)")
            continue
        dead = False
        if client.pid > 0 and client.pid_start_time > 0:
            st = proc_start_time(client.pid)
            dead = st is None or st != client.pid_start_time
        stale = bool(client.last_seen) and (now - client.last_seen) > observer.CLIENT_STALE_SECONDS
        if dead or stale:
            detail = "process dead (/proc)" if dead else "client heartbeat stale"
            print(f"client {client_id}: {client.status} {detail} (would raise stale-client)")
        else:
            print(f"client {client_id}: {client.status} alive (no escalation)")

    observations = observer.iter_observations(root)
    unsupported = sorted({o.predicate for o in observations if o.predicate in observer.UNSUPPORTED_PREDICATES})
    print(
        f"observations: {len(observations)} recent; unsupported predicates: "
        f"{', '.join(unsupported) if unsupported else 'none'}"
    )

    incidents = _read_incidents_readonly(root)
    open_count = sum(1 for i in incidents if i.get("phase") not in _TERMINAL_PHASES)
    print(f"incidents: {open_count} open, {len(incidents) - open_count} terminal")
    return 0


def _cmd_doctor(args) -> int:
    """Read-only report: ED-209 coverage, unsupported adapters, degraded policy."""
    rules_path = args.rules or ed209_cli.DEFAULT_RULES_PATH
    if not os.path.exists(rules_path):
        print("ed209 rules: absent")
        print("degraded: yes (rules document absent)")
    else:
        try:
            with open(rules_path, encoding="utf-8") as f:
                raw = json.load(f)
        except (OSError, ValueError) as exc:
            # Present but unreadable/corrupt: report corrupt (degraded), NEVER
            # conflate a present-but-broken file with an absent one.
            print(f"ed209 rules: corrupt ({exc})")
            print("degraded: yes (rules document unreadable)")
        else:
            if not isinstance(raw, dict):
                print("ed209 rules: corrupt (not a JSON object)")
                print("degraded: yes (rules document not an object)")
            else:
                doc = raw
                try:
                    rules = load_rules(doc)
                except RulesError as exc:
                    print(f"ed209 rules: invalid ({exc})")
                    print("degraded: yes (rules document failed schema validation)")
                    rules = []
                enabled = [r for r in rules if r.enabled]
                disabled = [r for r in rules if not r.enabled]
                print(f"ed209 rules: {len(enabled)} enabled, {len(disabled)} disabled")

                unbound: set[str] = set()
                unbound_mutating: set[str] = set()
                for r in enabled:
                    if r.action not in ("deny", "block") or not r.tools:
                        continue
                    specs = r.tools if isinstance(r.tools, (list, tuple, set)) else [r.tools]
                    for spec in specs:
                        if not isinstance(spec, str) or not spec.strip():
                            continue
                        if not capabilities.capabilities_for(spec):
                            unbound.add(spec)
                            if capabilities.looks_mutating(spec):
                                unbound_mutating.add(spec)
                if unbound:
                    print(f"unbound tool specifiers: {', '.join(sorted(unbound))}")
                else:
                    print("unbound tool specifiers: none")
                if unbound_mutating:
                    print(f"unbound mutating (degraded): {', '.join(sorted(unbound_mutating))}")
                print(f"degraded: {'yes' if unbound_mutating else 'no'}")

    print("r2d2 operations:")
    print(f"  executable: {', '.join(sorted(handlers.EXECUTABLE_OPERATIONS))}")
    # mcp_reconnect is IMPLEMENTED but CONDITIONAL (needs an owning-client IPC
    # adapter); it is not a static "unsupported" op.
    print(
        f"  conditional: {handlers.OP_MCP_RECONNECT} "
        "(implemented handler; requires an owning-client IPC adapter)"
    )
    for op in sorted(
        handlers.OPERATION_NAMES - handlers.EXECUTABLE_OPERATIONS - {handlers.OP_MCP_RECONNECT}
    ):
        reason = getattr(handlers.get_handler(op), "reason", None)
        print(f"  unsupported: {op} ({reason or 'no supported adapter'})")
    print(f"observer predicates unsupported: {', '.join(sorted(observer.UNSUPPORTED_PREDICATES))}")
    return 0


# ---------------------------------------------------------------------------
# Grant verbs (operator-only)
# ---------------------------------------------------------------------------

def _grants_dir(args) -> str:
    return os.path.join(args.root or DEFAULT_STATE_ROOT, "grants")


def _ledger_grant_refusal(args) -> None:
    db = getattr(args, "db", None) or DEFAULT_HITS_DB
    HitLedger(db).record_hit(
        rule_id=GRANT_VERB_DENY_RULE_ID,
        session_id="r2d2-grant-cli",
        outcome="deny",
        counted_fact="grant verb refused (operator-only, not daemon/model execution)",
        surface="tool",
        client_id="r2d2",
    )


def _grant_guard(args) -> None:
    """Refuse daemon/model execution of a grant verb and LEDGER the refusal."""
    if getattr(args, "recovery", False) or getattr(args, "automatic", False):
        _ledger_grant_refusal(args)
        raise OperatorActionRefused(
            "grant verbs are operator-only; automatic agent recovery is refused"
        )
    marker = (args.operator or "").strip().lower()
    if not marker:
        _ledger_grant_refusal(args)
        raise OperatorActionRefused("grant verbs require a non-empty --operator marker")
    if marker in GRANT_CLI_DENIED_MARKERS:
        _ledger_grant_refusal(args)
        raise OperatorActionRefused(
            f"operator marker {args.operator!r} presents as daemon/model execution; "
            f"refusing the grant verb"
        )


def _cmd_grant_issue(args) -> int:
    _grant_guard(args)
    store = GrantStore(_grants_dir(args))
    incident = _store(args).get_incident(args.incident)
    if incident is None:
        raise GrantError(f"no incident {args.incident!r} to grant against")
    grant = store.issue(
        incident_id=args.incident,
        scope=args.scope,
        session_id=args.session,
        client_id=args.client,
        pid=args.pid,
        start_time=args.start_time,
        issuer=args.operator,
        ttl_seconds=args.ttl_seconds,
    )
    print(f"{grant.grant_id}\t{grant.nonce}\t{grant.issued_at}\t{grant.expires_at}")
    return 0


def _cmd_grant_list(args) -> int:
    _grant_guard(args)
    grants = GrantStore(_grants_dir(args)).list_for_incident(args.incident)
    if not grants:
        print("(no grants)")
        return 0
    for g in grants:
        print(
            f"{g.grant_id}\t{g.scope}\t{g.issued_at}\t{g.expires_at}\t"
            f"consumed={g.consumed}\trevoked={g.revoked}"
        )
    return 0


def _cmd_grant_revoke(args) -> int:
    _grant_guard(args)
    grant = GrantStore(_grants_dir(args)).revoke(args.grant, operator=args.operator)
    print(f"{grant.grant_id}\trevoked={grant.revoked}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="r2d2",
        description="R2-D2 capability-recovery CLI (durable core + operator grants).",
    )
    p.add_argument("--root", help="state root dir (default: ~/.hermes/r2d2)")
    p.add_argument("--db", help="ED-209 hits.db path (grant-verb refusal ledger)")
    sub = p.add_subparsers(dest="verb", required=True)

    pr = sub.add_parser("raise", help="durably raise an incident (id printed after commit)")
    pr.add_argument("--id", required=True)
    pr.add_argument("--severity", required=True, choices=sorted(SEVERITIES))
    pr.add_argument("--symptom", required=True)
    pr.add_argument("--dedupe-key")
    pr.add_argument("--phase", choices=sorted(LIFECYCLE_PHASES), default="open")
    pr.add_argument("--host-id")
    pr.add_argument("--profile-id")
    pr.add_argument("--client-id")
    pr.add_argument("--session-id")
    pr.add_argument("--notification")
    pr.add_argument("--observed", nargs="*")
    pr.set_defaults(func=_cmd_raise)

    pd = sub.add_parser("done", help="close an incident (verified PASS or manual reason)")
    pd.add_argument("--id", required=True)
    pd.add_argument("--proof")
    pd.add_argument("--reason")
    pd.set_defaults(func=_cmd_done)

    ps = sub.add_parser("status", help="list committed incidents")
    ps.add_argument("--id")
    ps.set_defaults(func=_cmd_status)

    pe = sub.add_parser("events", help="list committed events")
    pe.add_argument("-n", "--limit", type=int)
    pe.set_defaults(func=_cmd_events)

    # -- watch (dry-run observer) + doctor (read-only report) ----------------
    pw = sub.add_parser(
        "watch", help="DRY-RUN observer: report what WOULD alert/escalate (never mutates)"
    )
    pw.set_defaults(func=_cmd_watch)

    pdoc = sub.add_parser(
        "doctor",
        help="read-only report: ED-209 coverage, unsupported adapters, degraded policy",
    )
    pdoc.add_argument(
        "--rules",
        help="rules JSON path for coverage analysis (default: runtime rules.json)",
    )
    pdoc.set_defaults(func=_cmd_doctor)

    # -- grant (operator-only; nested issue/list/revoke) ---------------------
    pg = sub.add_parser("grant", help="operator-only scoped kill grants")
    gsub = pg.add_subparsers(dest="grant_verb", required=True)

    issue = gsub.add_parser("issue", help="issue a scoped single-use TTL grant")
    issue.add_argument("--incident", required=True)
    issue.add_argument("--scope", required=True, choices=sorted(GRANT_SCOPES))
    issue.add_argument("--session", required=True)
    issue.add_argument("--client", required=True)
    issue.add_argument("--pid", required=True, type=int)
    issue.add_argument("--start-time", required=True, type=float)
    issue.add_argument("--ttl-seconds", type=int, default=1800)
    _add_operator_args(issue)
    issue.set_defaults(func=_cmd_grant_issue)

    glist = gsub.add_parser("list", help="list grants for an incident")
    glist.add_argument("--incident", required=True)
    _add_operator_args(glist)
    glist.set_defaults(func=_cmd_grant_list)

    revoke = gsub.add_parser("revoke", help="revoke a grant")
    revoke.add_argument("--grant", required=True)
    _add_operator_args(revoke)
    revoke.set_defaults(func=_cmd_grant_revoke)

    return p


def _add_operator_args(sp: argparse.ArgumentParser) -> None:
    sp.add_argument(
        "--operator", required=True,
        help="explicit operator marker (who is acting); recorded as provenance",
    )
    sp.add_argument(
        "--recovery", action="store_true",
        help="REFUSED: presents the action as automatic agent recovery",
    )
    sp.add_argument(
        "--automatic", action="store_true",
        help="REFUSED: presents the action as automatic agent recovery",
    )


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except (StoreError, StoreCorruptionError, IncidentError, GrantError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    except OperatorActionRefused as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
